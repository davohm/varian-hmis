import { handleAdminCommand } from "../_shared";

type RawInput = Record<string, unknown>;

const commands: Record<string, (input: RawInput) => Promise<unknown>> = {
  createFacility: (input) => createFacility(input as CreateFacilityInput),
  updateFacility: (input) => updateFacility(input as UpdateFacilityInput),
  setFacilityActive: (input) => setFacilityActive(input as SetFacilityActiveInput),
  createBranch: (input) => createBranch(input as CreateBranchInput),
  updateBranch: (input) => updateBranch(input as UpdateBranchInput),
  setBranchActive: (input) => setBranchActive(input as SetBranchActiveInput),
  createDepartment: (input) => createDepartment(input as CreateDepartmentInput),
  updateDepartment: (input) => updateDepartment(input as UpdateDepartmentInput),
  setDepartmentActive: (input) => setDepartmentActive(input as SetDepartmentActiveInput),
  createRoom: (input) => createRoom(input as CreateRoomInput),
  updateRoom: (input) => updateRoom(input as UpdateRoomInput),
  setRoomActive: (input) => setRoomActive(input as SetRoomActiveInput),
  createStore: (input) => createStore(input as Parameters<typeof createStore>[0]),
  updateStore: (input) => updateStore(input as Parameters<typeof updateStore>[0]),
  setStoreActive: (input) => setStoreActive(input as Parameters<typeof setStoreActive>[0]),
  changeStaffRole: (input) => changeStaffRole(input as ChangeStaffRoleInput),
  createStaff: (input) => createStaff(input as CreateStaffInput),
  updateStaff: (input) => updateStaff(input as UpdateStaffInput),
  setStaffActive: (input) => setStaffActive(input as SetStaffActiveInput),
  createItem: (input) => createItem(input as CreateItemInput),
  updateItem: (input) => updateItem(input as UpdateItemInput),
  setItemActive: (input) => setItemActive(input as SetItemActiveInput),
  createLabTest: (input) => createLabTest(input as CreateLabTestInput),
  updateLabTest: (input) => updateLabTest(input as UpdateLabTestInput),
  setLabTestActive: (input) => setLabTestActive(input as SetLabTestActiveInput),
  createService: (input) => createService(input as CreateServiceInput),
  updateService: (input) => updateService(input as UpdateServiceInput),
  setServiceActive: (input) => setServiceActive(input as SetServiceActiveInput),
  createPriceList: (input) => createPriceList(input as CreatePriceListInput),
  updatePriceList: (input) => updatePriceList(input as UpdatePriceListInput),
  setPriceListActive: (input) => setPriceListActive(input as SetPriceListActiveInput),
  upsertPrice: (input) => upsertPrice(input as UpsertPriceInput),
  removePrice: (input) => removePrice(input as RemovePriceInput),
  importIcd10: (input) => importIcd10(input as ImportIcd10Input),
};

export async function POST(request: NextRequest) {
  return handleAdminCommand(request, commands);
}

// Keep an explicit response for unsupported methods rather than a framework default.
export async function GET() {
  return NextResponse.json({ error: "Use POST for admin commands" }, { status: 405 });
}
