import { z } from "zod";

import { isOverridableTable } from "./overrides";
import { isInboundSyncTable, isOutboundSyncTable } from "./registry";

export const syncRowSchema = z.object({
  outboxId: z.uuid(),
  facilityId: z.uuid(),
  deviceKey: z.string().trim().min(1).max(128),
  tableName: z.string().refine(isOutboundSyncTable, "Table is not syncable"),
  recordId: z.string().trim().min(1).max(256),
  operation: z.enum(["INSERT", "UPDATE", "DELETE"]),
  payload: z.record(z.string(), z.unknown()),
  version: z.number().int().nonnegative().optional(),
});

export const syncBatchSchema = z.object({
  facilityId: z.uuid(),
  deviceKey: z.string().trim().min(1).max(128),
  rows: z.array(syncRowSchema).min(1).max(100),
});

export const pullRowSchema = z.object({
  tableName: z.string().refine(isInboundSyncTable, "Table is not pullable"),
  payload: z.record(z.string(), z.unknown()),
});

/**
 * Keyset cursor. updatedAt is the ISO-8601 (microsecond) value generated by
 * Postgres, and id is the last row's id. id = null means "only the timestamp
 * bound is known" (legacy checkpoint migration).
 */
export const pullCursorSchema = z.object({
  updatedAt: z.string().min(1).max(64),
  id: z.string().min(1).max(64).nullable(),
});

export const pullCursorsSchema = z.record(
  z.string().refine(isInboundSyncTable, "Table is not pullable"),
  pullCursorSchema,
);

/** A cloud proposal waiting for a branch admin decision. */
export const adminOverridePullSchema = z.object({
  id: z.uuid(),
  facilityId: z.uuid(),
  tableName: z.string().refine(isOverridableTable, "Table is not overrideable"),
  recordId: z.string().min(1),
  changes: z.record(z.string(), z.unknown()),
  basedOnVersion: z.number().int().positive(),
  reason: z.string(),
  requestedBy: z.string(),
  status: z.literal("proposed"),
  createdAt: z.string(),
  version: z.number().int().positive(),
});

export const overrideCursorSchema = z.object({
  createdAt: z.string().min(1).max(64),
  id: z.uuid(),
});

export const pullResponseSchema = z.object({
  rows: z.array(pullRowSchema),
  /** Omitted by an older cloud; the worker then falls back to the legacy checkpoint. */
  cursors: pullCursorsSchema.optional(),
  overrides: z.array(adminOverridePullSchema).default([]),
  overrideCursor: overrideCursorSchema.optional(),
  pulledAt: z.string(),
});

export type SyncRow = z.infer<typeof syncRowSchema>;
export type PullRow = z.infer<typeof pullRowSchema>;
export type PullCursor = z.infer<typeof pullCursorSchema>;
export type PullCursorMap = z.infer<typeof pullCursorsSchema>;
export type AdminOverridePull = z.infer<typeof adminOverridePullSchema>;
export type OverrideCursor = z.infer<typeof overrideCursorSchema>;
